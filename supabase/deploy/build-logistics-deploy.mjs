#!/usr/bin/env node
// Builds supabase/deploy/logistics_apply.sql: the 1145 Logistics migrations as
// ONE transaction for the Supabase SQL Editor (all or nothing).
//   node supabase/deploy/build-logistics-deploy.mjs
// Run logistics_preflight.sql first; see supabase/deploy/README.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const migDir = path.join(here, "..", "migrations");
const files = fs.readdirSync(migDir).filter((f) => /^2026111[67]\d+_logistics_.*\.sql$/.test(f)).sort();

const parts = [
  "-- =============================================================================",
  "-- 1145 Logistics: apply all logistics migrations in one transaction.",
  "-- GENERATED by supabase/deploy/build-logistics-deploy.mjs; do not edit by hand.",
  "-- Run supabase/deploy/logistics_preflight.sql first; every row must say ok.",
  "-- If any statement fails, nothing is applied.",
  "-- =============================================================================",
  "BEGIN;",
  "SET LOCAL statement_timeout = 0;",
  "SET LOCAL lock_timeout = '15s'; -- give up instead of queueing behind live traffic",
  "",
  "-- Refuse to run twice.",
  "DO $$ BEGIN",
  "  IF to_regclass('public.shipments') IS NOT NULL OR to_regclass('public.logistics_members') IS NOT NULL THEN",
  "    RAISE EXCEPTION '1145 Logistics is already installed in this database';",
  "  END IF;",
  "END $$;",
  "",
];
for (const f of files) {
  const sql = fs.readFileSync(path.join(migDir, f), "utf8").split("\r\n").join("\n").trimEnd();
  parts.push(`-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>> ${f}`, sql, "");
}
const versions = files.map((f) => `('${f.slice(0, 14)}', '${f.slice(15, -4)}')`).join(",\n    ");
parts.push(
  "-- Record the migrations so `supabase db push` never re-runs them.",
  "DO $$ BEGIN",
  "  IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN",
  "    INSERT INTO supabase_migrations.schema_migrations (version, name) VALUES",
  `    ${versions}`,
  "    ON CONFLICT (version) DO NOTHING;",
  "  END IF;",
  "END $$;",
  "",
  "COMMIT;",
  "",
  "-- After the commit: make the running pg_cron scheduler load the new jobs.",
  "-- Jobs created inside one large transaction were not picked up on the live",
  "-- project (2026-11-17) until each was touched with cron.alter_job.",
  "SELECT cron.alter_job(jobid, schedule := schedule, active := true)",
  "  FROM cron.job WHERE jobname LIKE 'logistics-%';",
  "",
);
const out = path.join(here, "logistics_apply.sql");
fs.writeFileSync(out, parts.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), out)} (${files.length} migrations):\n  ${files.join("\n  ")}`);
